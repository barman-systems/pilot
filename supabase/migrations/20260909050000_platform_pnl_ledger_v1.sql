-- DABBIR platform P&L ledger v1.
-- Tracks DABBIR's own revenue/costs only. Tenant/customer operational money is excluded.
-- Owner labor is intentionally excluded while DABBIR is operated by the solo owner.

create table if not exists dabbir_private.platform_finance_events (
  id bigint generated by default as identity primary key,
  source_event_key text not null unique,
  direction text not null check (direction in ('COST','REVENUE')),
  category text not null check (category in (
    'AI','WHATSAPP','HOSTING','DATABASE','STORAGE','MONITORING','INTEGRATION','MAPS',
    'APP_STORE_FEE','PAYMENT_FEE','DOMAIN','LEGAL','MARKETING','LABOR','OTHER',
    'SUBSCRIPTION_REVENUE','OTHER_REVENUE'
  )),
  provider text not null,
  business_id uuid references public.dabbir_businesses(id) on delete set null,
  amount numeric(20,6) not null check (amount >= 0),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  amount_aed numeric(20,6) not null check (amount_aed >= 0),
  authority text not null check (authority in (
    'PROVIDER_RECONCILED','PROVIDER_REPORTED','METERED_ACTUAL','MANUAL_VERIFIED','ESTIMATED'
  )),
  occurred_at timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  check (char_length(source_event_key) between 3 and 240),
  check (char_length(provider) between 1 and 120)
);

create index if not exists platform_finance_events_month_idx
  on dabbir_private.platform_finance_events (occurred_at desc);
create index if not exists platform_finance_events_business_month_idx
  on dabbir_private.platform_finance_events (business_id, occurred_at desc)
  where business_id is not null;
create index if not exists platform_finance_events_category_month_idx
  on dabbir_private.platform_finance_events (category, occurred_at desc);

alter table dabbir_private.platform_finance_events enable row level security;
alter table dabbir_private.platform_finance_events force row level security;
revoke all on dabbir_private.platform_finance_events from public, anon, authenticated;
revoke update, delete, truncate on dabbir_private.platform_finance_events from service_role;
grant select, insert on dabbir_private.platform_finance_events to service_role;

create table if not exists dabbir_private.platform_finance_sources (
  source_key text primary key,
  provider text not null,
  category text not null,
  capture_mode text not null check (capture_mode in ('AUTO_DERIVED','PROVIDER_SYNC','MANUAL_VERIFIED')),
  coverage_state text not null default 'UNCONFIRMED' check (coverage_state in ('AUTO','SYNCED','FREE','NOT_USED','UNCONFIRMED')),
  required_for_complete boolean not null default true,
  active boolean not null default true,
  note text,
  updated_at timestamptz not null default now(),
  check (char_length(source_key) between 3 and 120),
  check (char_length(provider) between 1 and 120)
);

alter table dabbir_private.platform_finance_sources enable row level security;
alter table dabbir_private.platform_finance_sources force row level security;
revoke all on dabbir_private.platform_finance_sources from public, anon, authenticated;
grant select, insert, update on dabbir_private.platform_finance_sources to service_role;

