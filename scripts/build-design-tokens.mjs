import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function tokenOutputs(tokens) {
  const declarations = values => Object.entries(values).map(([key, value]) => `--${key}:${value}`).join(';');
  const scale = (prefix, values) => Object.fromEntries(Object.entries(values).map(([key,value]) => [`${prefix}-${key}`,`${value}px`]));
  const common = {
    ...scale('space', tokens.spacing), ...scale('radius', tokens.radius), ...scale('font', tokens.typography.sizes),
    ...Object.fromEntries(Object.entries(tokens.touch).map(([key,value]) => [`touch-${key}`,`${value}px`])),
    ...Object.fromEntries(Object.entries(tokens.shadows).map(([key,value]) => [`shadow-${key}`,value])),
    'font-arabic':tokens.typography.webArabic, 'font-english':tokens.typography.webEnglish,
    ...Object.fromEntries(Object.entries(tokens.identity).flatMap(([role,values]) => Object.entries(values).map(([key,value]) => [`identity-${role}-${key}`,value]))),
    ...Object.fromEntries(Object.entries(tokens.chat || {}).map(([key,value]) => [`chat-${key}`,value])),
  };
  const css = '/* Generated by scripts/build-design-tokens.mjs. Edit design/tokens.json. */\n'
    + `:root{${declarations(common)}}\n`
    + `:root[data-dabbir-theme="web"]{${declarations({...tokens.web.base,...tokens.web.executive})}}\n`
    + `:root[data-dabbir-theme="booking"]{${declarations(tokens.web.base)}}\n`
    + `:root[data-dabbir-theme="team"]{${declarations(tokens.web.team)}}\n`;
  const native = { ...tokens.native, spacing:tokens.spacing, radius:tokens.radius, typography:tokens.typography, touch:tokens.touch };
  return {
    'public/dabbir-design-tokens.css':css,
    'mobile/src/design-tokens.ts':'// Generated by scripts/build-design-tokens.mjs. Edit design/tokens.json.\nexport const designTokens = '+JSON.stringify(native,null,2)+' as const;\n',
  };
}

export function buildTokens({ check=false, directory=root }={}) {
  const tokens=JSON.parse(fs.readFileSync(path.join(directory,'design/tokens.json'),'utf8'));
  for (const [file, expected] of Object.entries(tokenOutputs(tokens))) {
    const target=path.join(directory,file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==expected) throw new Error(`DESIGN_TOKEN_DRIFT: ${file}; run node scripts/build-design-tokens.mjs`);
    } else fs.writeFileSync(target,expected);
  }
}
if (process.argv[1] && path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) buildTokens({check:process.argv.includes('--check')});
